const checkedTechniques = new Set([SolutionTechniqueEnum.EmptyRectangle, SolutionTechniqueEnum.ALSXZ, SolutionTechniqueEnum.SueDeCoq]);
const checkedStrategies = createTechniqueStrategies().filter(strategy => checkedTechniques.has(strategy.technique));
const soundnessTimeoutMilliseconds = 120_000;

const getSolvePathContexts = (sudoku: Sudoku): CandidateContext[] => {
    const contexts = [CandidateContext.fromSudoku(sudoku)];

    for (const step of new TechniqueManager(sudoku).solveLogically().steps) {
        contexts.push(applyTechniqueStep(contexts[contexts.length - 1], step));
    }

    return contexts;
};

const findUnsoundResults = (puzzle: string): string[] => {
    const sudoku = Sudoku.fromString(puzzle, defaultSudokuConfig);

    return getSolvePathContexts(sudoku).flatMap(context =>
        checkedStrategies.flatMap(strategy =>
            strategy
                .find(context)
                .flatMap(result => [
                    ...result.eliminations
                        .filter(elimination => elimination.value === sudoku.getCorrectValue(elimination.cell))
                        .map(
                            ({ cell, value }) =>
                                `${puzzle} ${SolutionTechniqueEnum[strategy.technique]} eliminates ${value} at r${cell.y + 1}c${cell.x + 1}`
                        ),
                    ...(result.kind === 'placement' && result.value !== sudoku.getCorrectValue(result.cell)
                        ? [
                              `${puzzle} ${SolutionTechniqueEnum[strategy.technique]} places ${result.value} at r${result.cell.y + 1}c${result.cell.x + 1}`
                          ]
                        : [])
                ])
        )
    );
};

describe('advanced technique soundness along logical solve paths', () => {
    it.each([
        ['Hell corpus', hellCorpusSample],
        ['Nightmare', nightmareSample]
    ])(
        'never removes the solution digit or places a wrong digit on %s boards',
        (_, puzzles) => {
            expect(puzzles.flatMap(findUnsoundResults)).toEqual([]);
        },
        soundnessTimeoutMilliseconds
    );
});
