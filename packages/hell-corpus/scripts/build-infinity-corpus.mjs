import { readFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

import { BitmaskSolver } from '@suuudokuuu/solver-bitmask';
import { DLXSolver } from '@suuudokuuu/solver-dlx';

import { writeGeneratedCorpusModule } from './shared/generated-module-writer.mjs';
import { encodeRatingByte, packPuzzleRecord } from './shared/record-packing.mjs';
import { isSinglesSolvable } from './shared/singles-solvability.mjs';
import { crossCheckPuzzleLine, lineToGrid, validatePuzzleFormat, validateUniquePuzzle } from './shared/puzzle-verification.mjs';

const SCRIPT_DIRECTORY = dirname(fileURLToPath(import.meta.url));
const SOURCE_FILE = join(SCRIPT_DIRECTORY, 'infinity-corpus-source.json');
const OUTPUT_FILE = join(SCRIPT_DIRECTORY, '..', 'src', 'constants', 'infinity-corpus-data.constant.ts');

const MINIMUM_RATING = 10.0;
const MAXIMUM_GIVEN_COUNT = 23;
const POSITION_MASK_BYTES = 11;
const RECORD_BYTES = POSITION_MASK_BYTES + Math.ceil(MAXIMUM_GIVEN_COUNT / 2) + 1;
const RECORD_BASE64_LENGTH = Math.ceil(RECORD_BYTES / 3) * 4;
const MAX_REPORTED_FAILURES = 20;

const GENERATED_FILE_HEADER = `// Generated by packages/hell-corpus/scripts/build-infinity-corpus.mjs from
// packages/hell-corpus/scripts/infinity-corpus-source.json. Do not edit by hand.
//
// The curated Infinity corpus collects publicly documented, world-record-class hard
// sudoku puzzles (Sudoku Explainer rating >= 10.0), including Arto Inkala's "Everest"
// and "AI Escargot", and the "Platinum Blonde" puzzle studied in Ercsey-Ravasz &
// Toroczkai, "The Chaos Within Sudoku" (Scientific Reports, 2012). Each entry's grid
// and rating are sourced in packages/hell-corpus/scripts/infinity-corpus-source.json.
// Ratings are the puzzle authors'/publications' claimed Sudoku Explainer ratings,
// trusted as external published values until this project's own forcing-chain rater
// can verify them in-house.`;

const readSourcePuzzles = () => {
    const sourceText = readFileSync(SOURCE_FILE, 'utf8');
    const parsed = JSON.parse(sourceText);

    if (!Array.isArray(parsed)) {
        throw new Error(`${SOURCE_FILE}: expected a JSON array of curated puzzles`);
    }

    return parsed;
};

const describeEntry = (entry, entryIndex) => `entry ${entryIndex}${entry?.name ? ` (${entry.name})` : ''}`;

const validateInfinitySourceEntry = (entry, entryIndex, seenPuzzles, bitmaskSolver) => {
    const entryLabel = describeEntry(entry, entryIndex);

    if (typeof entry.name !== 'string' || entry.name.length === 0) {
        return `${entryLabel}: missing "name"`;
    }

    if (typeof entry.grid !== 'string') {
        return `${entryLabel}: missing "grid"`;
    }

    if (typeof entry.rating !== 'number') {
        return `${entryLabel}: missing "rating"`;
    }

    if (typeof entry.source !== 'string' || entry.source.length === 0) {
        return `${entryLabel}: missing "source"`;
    }

    const formatFailure = validatePuzzleFormat(entry.grid, entryLabel);

    if (formatFailure) {
        return formatFailure;
    }

    if (entry.rating < MINIMUM_RATING) {
        return `${entryLabel}: rating ${entry.rating} is below the ${MINIMUM_RATING} Infinity threshold`;
    }

    const givenCount = lineToGrid(entry.grid).reduce((count, value) => (value === 0 ? count : count + 1), 0);

    if (givenCount > MAXIMUM_GIVEN_COUNT) {
        return `${entryLabel}: has ${givenCount} givens, exceeding the packed record capacity of ${MAXIMUM_GIVEN_COUNT}`;
    }

    return validateUniquePuzzle(entry.grid, entryLabel, seenPuzzles, bitmaskSolver);
};

const main = () => {
    const startTime = Date.now();
    const sourcePuzzles = readSourcePuzzles();

    const bitmaskSolver = new BitmaskSolver();
    const dlxSolver = new DLXSolver();
    const seenPuzzles = new Set();
    const failures = [];
    const records = [];
    let singlesSolvableCount = 0;

    sourcePuzzles.forEach((entry, entryIndex) => {
        const entryLabel = describeEntry(entry, entryIndex);
        const failure = validateInfinitySourceEntry(entry, entryIndex, seenPuzzles, bitmaskSolver);

        if (failure) {
            failures.push(failure);

            return;
        }

        const crossCheckFailure = crossCheckPuzzleLine(entry.grid, entryLabel, dlxSolver);

        if (crossCheckFailure) {
            failures.push(crossCheckFailure);

            return;
        }

        if (isSinglesSolvable(lineToGrid(entry.grid))) {
            singlesSolvableCount += 1;
            failures.push(`${entryLabel}: unexpectedly solvable with singles alone`);

            return;
        }

        records.push(packPuzzleRecord(entry.grid, encodeRatingByte(entry.rating), RECORD_BYTES));
    });

    if (failures.length > 0) {
        console.error(`Infinity corpus build failed with ${failures.length} issue(s):`);
        failures.slice(0, MAX_REPORTED_FAILURES).forEach(failure => console.error(` - ${failure}`));
        process.exitCode = 1;

        return;
    }

    writeGeneratedCorpusModule({
        outputFile: OUTPUT_FILE,
        header: GENERATED_FILE_HEADER,
        sizeName: 'INFINITY_CORPUS_SIZE',
        size: records.length,
        base64Name: 'INFINITY_CORPUS_BASE64',
        base64: records.join('')
    });

    const elapsedMs = Date.now() - startTime;
    const totalBytes = records.length * RECORD_BYTES;
    const base64Length = records.length * RECORD_BASE64_LENGTH;

    console.log('Infinity corpus build summary');
    console.log(`  puzzles verified: ${sourcePuzzles.length}`);
    console.log(`  singles-solvable excluded: ${singlesSolvableCount}`);
    console.log(`  puzzles kept: ${records.length}`);
    console.log(`  failures: ${failures.length}`);
    console.log(`  record bytes: ${RECORD_BYTES}`);
    console.log(`  raw bytes: ${totalBytes}`);
    console.log(`  base64 characters: ${base64Length}`);
    console.log(`  elapsed: ${elapsedMs}ms`);
};

try {
    main();
} catch (error) {
    console.error(error instanceof Error ? error.message : String(error));
    process.exitCode = 1;
}
